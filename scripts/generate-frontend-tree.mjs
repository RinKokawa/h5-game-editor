#!/usr/bin/env node
/**
 * generate-frontend-tree.mjs — 扫 src/ 输出前端层级骨架片段。
 *
 * 用法：node scripts/generate-frontend-tree.mjs [--out <file>]
 *   默认输出到 stdout。可被 docs/frontend-structure.md 引用，
 *   也可以跑一遍验证 §2-§4 是否漂移。
 *
 * 输出三块：
 *   1. src/ 的文件树（剥 .git / node_modules / dist）。
 *   2. CSS Module 文件清单。
 *   3. PixiJS 场景图系统清单（canvas/ 下子目录）。
 *
 * 这不是文档生成器 — 它只输出**结构骨架**。意图说明、跨层关系
 * 等手写内容仍然在 docs/frontend-structure.md 里。
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'src';
const EXCLUDE = new Set([
  'node_modules',
  'dist',
  'dist-electron',
  '.vite',
  'coverage',
  'release',
  '.git',
]);

function isDir(p) {
  try {
    return statSync(p).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Walk a directory and emit a tree.
 *   prefix=""         → top level (no connector)
 *   prefix="│   "    → child of previous sibling
 *   prefix="    "    → last sibling (no further siblings below)
 */
function walk(dir, prefix = '') {
  const entries = readdirSync(dir)
    .filter((n) => !EXCLUDE.has(n))
    .sort((a, b) => a.localeCompare(b));
  const lines = [];
  for (let i = 0; i < entries.length; i++) {
    const name = entries[i];
    const isLast = i === entries.length - 1;
    const connector = isLast ? '└── ' : '├── ';
    const childPrefix = prefix + (isLast ? '    ' : '│   ');
    const full = join(dir, name);
    if (isDir(full)) {
      lines.push(prefix + connector + name + '/');
      lines.push(...walk(full, childPrefix));
    } else {
      lines.push(prefix + connector + name);
    }
  }
  return lines;
}

function filterExt(ext) {
  return (lines) => lines.filter((l) => l.endsWith(ext));
}

const srcAbs = ROOT;
if (! isDir(srcAbs)) {
  console.error(`error: ${srcAbs}/ not found (cwd: ${process.cwd()})`);
  process.exit(1);
}

const tree = walk(srcAbs);
const cssModules = filterExt('.module.css')(tree);
const tsxFiles = filterExt('.tsx')(tree);
const tsFiles = filterExt('.ts')(tree).filter((l) => ! l.includes('/index.ts'));

const output = [
  '# Auto-generated by scripts/generate-frontend-tree.mjs',
  '# 不要手改本节 — 重跑脚本刷新。',
  '',
  '## A. src/ 文件树',
  '',
  '```',
  `${ROOT}/`,
  ...tree,
  '```',
  '',
  '## B. CSS Module 文件',
  '',
  '```',
  ...cssModules,
  '```',
  '',
  '## C. React 组件（.tsx）',
  '',
  '```',
  ...tsxFiles,
  '```',
  '',
  '## D. 非 barrel TypeScript（.ts，去掉每个目录的 index.ts）',
  '',
  '```',
  ...tsFiles,
  '```',
  '',
];

const text = output.join('\n');

const outIdx = process.argv.indexOf('--out');
if (outIdx !== -1 && process.argv[outIdx + 1]) {
  const outPath = process.argv[outIdx + 1];
  writeFileSync(outPath, text, 'utf8');
  console.error(`wrote ${text.length} chars to ${outPath}`);
} else {
  process.stdout.write(text);
}